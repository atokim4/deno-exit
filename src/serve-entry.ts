import { existsSync, readFileSync } from "node:fs";
import { basename, dirname, extname, join } from "node:path";
import { ts } from "ts-morph";

/** How the module that `deno serve` runs exports its handler. */
export type DefaultExport = { kind: "fetch-object" } | { kind: "app"; name: string };

/** Constructors whose instances have a Fetch-API `fetch(request)` method (Hono and its OpenAPI variant). */
const APP_CONSTRUCTORS = /^(?:Hono|OpenAPIHono)$/;

/**
 * `deno serve` imports the module and serves its default export, which must be `{ fetch }` (docs.deno.com/runtime/
 * reference/cli/serve). Node has no such command, so an entry file has to call serve(). This only says yes when the
 * shape is clear from the source: an object literal with `fetch`, or a variable created with `new Hono()`.
 */
export function readDefaultExport(text: string, fileName: string): DefaultExport | null {
  const sf = ts.createSourceFile(fileName, text, ts.ScriptTarget.Latest, false, fileName.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const appVars = new Set<string>();
  let result: DefaultExport | null = null;
  const hasFetch = (obj: ts.ObjectLiteralExpression): boolean =>
    obj.properties.some((p) => p.name && ts.isIdentifier(p.name) && p.name.text === "fetch") ||
    obj.properties.some((p) => ts.isShorthandPropertyAssignment(p) && p.name.text === "fetch");
  const unwrap = (e: ts.Expression): ts.Expression => (ts.isSatisfiesExpression(e) || ts.isAsExpression(e) || ts.isParenthesizedExpression(e) ? unwrap(e.expression) : e);

  for (const st of sf.statements) {
    if (ts.isVariableStatement(st)) {
      for (const d of st.declarationList.declarations) {
        const init = d.initializer && unwrap(d.initializer);
        if (ts.isIdentifier(d.name) && init && ts.isNewExpression(init) && ts.isIdentifier(init.expression) && APP_CONSTRUCTORS.test(init.expression.text)) {
          appVars.add(d.name.text);
        }
      }
    }
    if (ts.isExportAssignment(st) && !st.isExportEquals) {
      const e = unwrap(st.expression);
      if (ts.isObjectLiteralExpression(e) && hasFetch(e)) result = { kind: "fetch-object" };
      else if (ts.isIdentifier(e) && appVars.has(e.text)) result = { kind: "app", name: e.text };
      else result = null;
    }
  }
  return result;
}

export interface ServeEntry {
  /** Path of the generated entry, relative to the package directory. */
  file: string;
  text: string;
}

/**
 * Builds `<name>.node.ts` next to the module: it imports the default export and serves it with @hono/node-server.
 * Deno serve listens on port 8000 by default; `--port` from the task becomes the default for PORT.
 */
export function buildServeEntry(packageDir: string, script: string, port: number, root: string): ServeEntry | null {
  const rel = script.replace(/^\.\//, "");
  const abs = join(root, packageDir, rel);
  if (!/\.[cm]?[jt]sx?$/.test(rel) || !existsSync(abs)) return null;
  const shape = readDefaultExport(readFileSync(abs, "utf8"), rel);
  if (!shape) return null;
  const ext = extname(rel);
  const isTs = /tsx?$/.test(ext);
  const file = join(dirname(rel), `${basename(rel, ext)}.node${isTs ? ".ts" : ext === ".jsx" ? ".js" : ext}`);
  const fetch = shape.kind === "app" ? "handler.fetch" : isTs ? "(request: Request) => handler.fetch(request)" : "(request) => handler.fetch(request)";
  const text = [
    "// Node entry for `deno serve`, generated by deno-exit: serves the module's default export.",
    'import { serve } from "@hono/node-server";',
    `import handler from "./${basename(rel)}";`,
    "",
    `const port = Number(process.env.PORT ?? ${port});`,
    "",
    `serve({ fetch: ${fetch}, port }, (info) => {`,
    "  console.log(`Listening on http://localhost:${info.port}/`);",
    "});",
    "",
  ].join("\n");
  return { file, text };
}
